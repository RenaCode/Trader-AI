import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const errs = [];
p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
p.on('pageerror', e => errs.push('PAGEERROR: ' + e.message + '\n' + (e.stack||'').split('\n').slice(0,4).join('\n')));
await p.goto('https://trader.renacode.com', { waitUntil: 'networkidle' });
await p.fill('input[autocomplete="username"]', 'admin');
await p.fill('input[autocomplete="current-password"]', process.env.TRADER_PASS);
await p.click('button[type="submit"]');
await p.waitForTimeout(4000);
console.log('ROOT innerHTML (300 zn.):', (await p.locator('#root').innerHTML()).slice(0, 300) || '(PUSTE)');
console.log('\nBLEDY:');
console.log(errs.length ? errs.join('\n---\n') : 'brak');
await b.close();
